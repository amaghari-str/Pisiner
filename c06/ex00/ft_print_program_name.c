#include <unistd.h>

int	main(int a, char *argv[])
{
	int	i;

	i = 0;
	a = a - 1;
	while (argv[0][i] != '\0')
	{
		write (1, &argv[0][i], 1);
		i++;
	}
	write (1, "\n", 1);
	return (0);
}
