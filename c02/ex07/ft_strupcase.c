#include <unistd.h>

char	*ft_strupcase(char *str)
{
	int	i;
	int	a;

	i = 0;
	while (str[i] != '\0')
	{
		a = str[i];
		if (a >= 97 && a <= 122)
		{
			str[i] = str[i] - 32;
		}
		i++;
	}
	return (str);
}
