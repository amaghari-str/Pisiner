#include <unistd.h>

int	ft_str_is_uppercase(char *str)
{
	int	i;
	int	a;

	i = 0;
	if (str[i] == '\0')
	{
		return (1);
	}
	while (str[i] != '\0')
	{
		a = str[i];
		if (!(a >= 65 && a <= 90))
		{
			return (0);
		}
		i++;
	}
	return (1);
}
